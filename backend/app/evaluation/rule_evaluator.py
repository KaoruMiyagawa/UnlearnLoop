"""Deterministic local rule pre-evaluator for UnlearnLoop Stage 3.

Per Stage 3 Section 2:
- Prioritizes local rule evaluation for questions with deterministic answers/rubrics.
- Emits rule results strictly as source-tracked evidence (`source_type="rule_check"`),
  NEVER jumping directly to a single final misconception conclusion.
- Flags when Agent model analysis and discriminating follow-up are required.
"""

from dataclasses import dataclass, field
from typing import Any

from app.domain.enums import (
    EvidenceRelation,
    EvidenceSourceType,
    HypothesisStatus,
    QuestionRole,
)
from app.persistence.models import Attempt, KnowledgeTopic, Question


@dataclass(frozen=True)
class RuleEvidenceDraft:
    """Draft evidence generated by local deterministic rule checks."""

    target_error_code: str
    source_type: EvidenceSourceType
    source_ref: str
    relation: EvidenceRelation
    summary: str
    reliability_note: str


@dataclass(frozen=True)
class RuleHypothesisDraft:
    """Draft candidate error hypothesis suggested by local rubric matching."""

    error_code: str
    name: str
    description: str
    heuristic_confidence: float
    initial_status: HypothesisStatus
    missing_evidence_desc: str


@dataclass(frozen=True)
class RuleEvaluationResult:
    """Structured result of running local rule pre-evaluation on an Attempt."""

    attempt_id: str
    question_id: str
    question_role: QuestionRole
    answer_matches_standard: bool
    has_reasoning_or_trace: bool
    is_fully_verified_correct: bool
    requires_agent_diagnosis: bool
    summary: str
    candidate_hypotheses: list[RuleHypothesisDraft] = field(default_factory=list)
    evidence_drafts: list[RuleEvidenceDraft] = field(default_factory=list)


def _normalize_text(text: str) -> str:
    return " ".join(text.strip().split())


def _has_explanation_beyond_output(answer: str, expected_output: str) -> bool:
    """Check if the learner provided reasoning/step trace beyond just the bare final output."""
    norm_ans = _normalize_text(answer)
    norm_exp = _normalize_text(expected_output)
    if norm_ans == norm_exp:
        return False
    remainder = norm_ans.replace(norm_exp, "", 1).strip(" ，,。.、:：;；")
    return len(remainder) >= 6


class RuleEvaluator:
    """Deterministic pre-evaluator producing source-attributed rule evidence and competing candidates."""

    def evaluate_attempt(
        self,
        *,
        attempt: Attempt,
        question: Question,
        topic: KnowledgeTopic,
    ) -> RuleEvaluationResult:
        rubric: dict[str, Any] = question.evaluation_rubric or {}
        expected_out = str(
            rubric.get("expected_output") or question.standard_answer
        ).strip()
        submitted = attempt.submitted_answer.strip()
        norm_submitted = _normalize_text(submitted)
        norm_expected = _normalize_text(expected_out)
        norm_std = _normalize_text(question.standard_answer)

        # A reasoning suffix needs a token boundary: expected "6" must not accept "60".
        answer_matches = (
            norm_submitted == norm_expected
            or norm_submitted == norm_std
            or (
                norm_expected != ""
                and norm_submitted.startswith(norm_expected)
                and len(norm_submitted) > len(norm_expected)
                and norm_submitted[len(norm_expected)] in " ，,。.、:：;；()（）"
            )
        )
        has_trace = _has_explanation_beyond_output(submitted, expected_out)

        mappings: list[dict[str, Any]] = list(
            rubric.get("candidate_error_mappings") or []
        )
        checks_no_trace = any(
            "(no trace)" in str(m.get("observed_answer_pattern", ""))
            for m in mappings
        )

        # Build lookup of topic error patterns
        topic_patterns: dict[str, dict[str, Any]] = {
            str(p["error_code"]): p
            for p in (topic.common_error_patterns or [])
            if "error_code" in p
        }

        role_enum = QuestionRole(question.question_role)
        rule_ref = f"rule_eval:{question.id}:{attempt.id}"

        candidate_hypotheses: list[RuleHypothesisDraft] = []
        evidence_drafts: list[RuleEvidenceDraft] = []
        seen_codes: set[str] = set()

        def _register_candidate(
            code: str,
            *,
            confidence: float,
            status: HypothesisStatus,
            missing_desc: str,
            ev_relation: EvidenceRelation,
            ev_summary: str,
        ) -> None:
            pat = topic_patterns.get(code, {})
            name = str(pat.get("name") or f"候选错误模式：{code}")
            desc = str(
                pat.get("description")
                or f"与知识点 {topic.slug} 相关的候选错误假设 ({code})。"
            )
            if code not in seen_codes:
                seen_codes.add(code)
                candidate_hypotheses.append(
                    RuleHypothesisDraft(
                        error_code=code,
                        name=name,
                        description=desc,
                        heuristic_confidence=min(max(confidence, 0.05), 0.70),
                        initial_status=status,
                        missing_evidence_desc=missing_desc,
                    )
                )
            evidence_drafts.append(
                RuleEvidenceDraft(
                    target_error_code=code,
                    source_type=EvidenceSourceType.RULE_CHECK,
                    source_ref=rule_ref,
                    relation=ev_relation,
                    summary=ev_summary,
                    reliability_note="Deterministic local rubric rule check (heuristic, non-conclusive)",
                )
            )

        # Case 1: Output matches standard answer, but trace/reasoning is missing when required
        if answer_matches and checks_no_trace and not has_trace:
            for m in mappings:
                pattern_str = str(m.get("observed_answer_pattern", ""))
                code = str(m.get("target_error_code", "")).strip()
                clue = str(
                    m.get("clue")
                    or "仅给出最终输出，缺少中间执行过程证据。"
                )
                if not code:
                    continue
                if "(no trace)" in pattern_str:
                    _register_candidate(
                        code,
                        confidence=0.46,
                        status=HypothesisStatus.INSUFFICIENT_EVIDENCE,
                        missing_desc="需要追问每轮中间状态以确认是否真正理解执行过程",
                        ev_relation=EvidenceRelation.SUPPORTS,
                        ev_summary="规则检查：作答结果匹配，但未提供中间过程说明。",
                    )

            # Also retain competing topic patterns as low-confidence candidates (e.g., range(3)=[1,2] sum=3)
            for code in topic_patterns:
                if code not in seen_codes:
                    _register_candidate(
                        code,
                        confidence=0.31,
                        status=HypothesisStatus.INSUFFICIENT_EVIDENCE,
                        missing_desc="当前仅有最终结果，需区分性追问排除巧合得数",
                        ev_relation=EvidenceRelation.NEUTRAL,
                        ev_summary=f"规则检查：仅凭单一输出结果尚不足以排除竞争性假设 '{code}'。",
                    )

            return RuleEvaluationResult(
                attempt_id=attempt.id,
                question_id=question.id,
                question_role=role_enum,
                answer_matches_standard=True,
                has_reasoning_or_trace=False,
                is_fully_verified_correct=False,
                requires_agent_diagnosis=True,
                summary="输出结果匹配标准答案，但缺少执行过程解释，存在多个竞争性假设需追问区分。",
                candidate_hypotheses=candidate_hypotheses,
                evidence_drafts=evidence_drafts,
            )

        # Case 2: Output does NOT match standard answer
        if not answer_matches:
            matched_any_rubric = False
            for m in mappings:
                obs_pat = _normalize_text(
                    str(m.get("observed_answer_pattern", ""))
                )
                code = str(m.get("target_error_code", "")).strip()
                clue = str(m.get("clue") or "作答与错误模式特征匹配。")
                if not code:
                    continue
                if obs_pat and obs_pat == norm_submitted:
                    matched_any_rubric = True
                    _register_candidate(
                        code,
                        confidence=0.55,
                        status=HypothesisStatus.CANDIDATE,
                        missing_desc="需通过区分性追问验证该错误假设是否成立",
                        ev_relation=EvidenceRelation.SUPPORTS,
                        ev_summary="规则检查：作答与一个候选错误模式相符，仍需追问验证。",
                    )
                else:
                    _register_candidate(
                        code,
                        confidence=0.35,
                        status=HypothesisStatus.INSUFFICIENT_EVIDENCE,
                        missing_desc="需要更多追问证据区分具体错误原因",
                        ev_relation=EvidenceRelation.NEUTRAL,
                        ev_summary=f"规则检查：作答未匹配标准答案，保留候选假设 '{code}' 待区分。",
                    )

            # Ensure all topic error patterns are considered as competing hypotheses
            for code in topic_patterns:
                if code not in seen_codes:
                    _register_candidate(
                        code,
                        confidence=0.30 if matched_any_rubric else 0.40,
                        status=HypothesisStatus.INSUFFICIENT_EVIDENCE,
                        missing_desc="证据不足，需通过诊断追问收集区分性证据",
                        ev_relation=EvidenceRelation.SUPPORTS
                        if not matched_any_rubric
                        else EvidenceRelation.NEUTRAL,
                        ev_summary=f"规则检查：本次作答未通过评价，纳入竞争性假设 '{code}'。",
                    )

            return RuleEvaluationResult(
                attempt_id=attempt.id,
                question_id=question.id,
                question_role=role_enum,
                answer_matches_standard=False,
                has_reasoning_or_trace=has_trace,
                is_fully_verified_correct=False,
                requires_agent_diagnosis=True,
                summary=f"规则检查发现作答与标准答案不一致，已生成 {len(candidate_hypotheses)} 个并列候选错误假设待 Agent 诊断。",
                candidate_hypotheses=candidate_hypotheses,
                evidence_drafts=evidence_drafts,
            )

        # Case 3: Answer matches standard answer and satisfies trace/role expectations
        for code in list(rubric.get("target_error_codes") or topic_patterns.keys()):
            code_str = str(code)
            _register_candidate(
                code_str,
                confidence=0.10,
                status=HypothesisStatus.LOWERED,
                missing_desc="无（当前作答证据反对该错误假设）",
                ev_relation=EvidenceRelation.CONTRADICTS,
                ev_summary=f"规则检查：作答 '{submitted}' 与标准答案一致，提供反对错误假设 '{code_str}' 的证据。",
            )

        return RuleEvaluationResult(
            attempt_id=attempt.id,
            question_id=question.id,
            question_role=role_enum,
            answer_matches_standard=True,
            has_reasoning_or_trace=True,
            is_fully_verified_correct=True,
            requires_agent_diagnosis=(role_enum != QuestionRole.TRANSFER_CHECK),
            summary="规则检查确认本次作答匹配标准答案及要求。",
            candidate_hypotheses=candidate_hypotheses,
            evidence_drafts=evidence_drafts,
        )
